#!/usr/bin/env node
/**
 * embed-dictionary.mjs
 * --------------------
 * Reads the Hunspell `.aff` / `.dic` files from the installed `dictionary-en`
 * package, gzip-compresses them, base64-encodes the result, and emits a
 * self-contained ES module (`src/generated/dict-data.ts`) that decodes the data
 * back into `{ aff, dic }` at load time using Node's built-in `zlib`.
 *
 * This lets esbuild inline the dictionary into a single `dist/tui.mjs`, so the
 * plugin needs no runtime `bun install` and no on-disk dictionary files.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { gzipSync } from "node:zlib"
import { fileURLToPath } from "node:url"
import path from "node:path"

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, "..")

function findDict(name) {
  const candidates = [
    path.join(root, "node_modules", "dictionary-en", name),
    path.join(root, "..", "node_modules", "dictionary-en", name),
  ]
  for (const c of candidates) {
    try {
      return readFileSync(c)
    } catch {
      /* try next */
    }
  }
  throw new Error(
    `Could not find dictionary-en/${name}. Run \`npm install dictionary-en\` first.`,
  )
}

const aff = findDict("index.aff")
const dic = findDict("index.dic")

const affB64 = gzipSync(aff, { level: 9 }).toString("base64")
const dicB64 = gzipSync(dic, { level: 9 }).toString("base64")

const out = `/* AUTO-GENERATED by scripts/embed-dictionary.mjs — do not edit. */
/* eslint-disable */
import { gunzipSync } from "node:zlib"

const AFF_GZ_B64 = ${JSON.stringify(affB64)}
const DIC_GZ_B64 = ${JSON.stringify(dicB64)}

// Return a Node Buffer (not a bare Uint8Array): nspell/Hunspell parsing relies
// on Buffer/string semantics and mis-parses a plain Uint8Array.
function decode(b64: string): Buffer {
  return gunzipSync(Buffer.from(b64, "base64"))
}

export const embeddedDictionary = {
  get aff(): Buffer {
    return decode(AFF_GZ_B64)
  },
  get dic(): Buffer {
    return decode(DIC_GZ_B64)
  },
}
`

const outDir = path.join(root, "src", "generated")
mkdirSync(outDir, { recursive: true })
writeFileSync(path.join(outDir, "dict-data.ts"), out, "utf8")

const kb = (n) => (n / 1024).toFixed(0)
console.log(
  `embedded dictionary → src/generated/dict-data.ts  ` +
    `(aff ${kb(aff.length)}KB→${kb(Buffer.byteLength(affB64, "base64"))}KB gz, ` +
    `dic ${kb(dic.length)}KB→${kb(Buffer.byteLength(dicB64, "base64"))}KB gz)`,
)
